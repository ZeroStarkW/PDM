CREATE TABLE pdm_factory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factory_code VARCHAR(32) NOT NULL UNIQUE,
    factory_name VARCHAR(128) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pdm_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factory_id BIGINT NOT NULL REFERENCES pdm_factory(id) ON DELETE CASCADE,
    device_code VARCHAR(64) NOT NULL,
    device_name VARCHAR(128) NOT NULL,
    rpm_nominal NUMERIC(8,2) NOT NULL DEFAULT 1500.00,
    power_kw NUMERIC(8,2),
    iso_class VARCHAR(16) NOT NULL DEFAULT 'CLASS_II',
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_factory_device UNIQUE(factory_id, device_code)
);

CREATE TABLE pdm_measurement_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES pdm_device(id) ON DELETE CASCADE,
    point_code VARCHAR(64) NOT NULL,
    point_name VARCHAR(128) NOT NULL,
    sensor_mac VARCHAR(32),
    freq_1x_base DOUBLE PRECISION,
    v_base_rms DOUBLE PRECISION,
    a_base_peak DOUBLE PRECISION,
    temp_base DOUBLE PRECISION,
    baseline_status SMALLINT NOT NULL DEFAULT 0,
    learned_samples INTEGER NOT NULL DEFAULT 0,
    baseline_locked_at TIMESTAMPTZ,
    last_health_index DOUBLE PRECISION,
    last_status VARCHAR(32),
    last_telemetry_at TIMESTAMPTZ,
    last_received_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_device_point UNIQUE(device_id, point_code)
);

CREATE INDEX idx_device_factory_status ON pdm_device(factory_id, status);
CREATE INDEX idx_point_baseline_status ON pdm_measurement_point(baseline_status);
