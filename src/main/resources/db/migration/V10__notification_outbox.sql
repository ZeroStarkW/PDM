CREATE TABLE pdm_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL REFERENCES pdm_alert_event(id),
    event_kind VARCHAR(16) NOT NULL CHECK (event_kind IN ('ALERT', 'ESCALATION')),
    payload JSONB NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING', 'DELIVERED', 'FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 8),
    next_attempt_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    last_error VARCHAR(160),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ,
    UNIQUE (alert_id, event_kind),
    CHECK ((state = 'PENDING') = (next_attempt_at IS NOT NULL)),
    CHECK ((state = 'DELIVERED') = (sent_at IS NOT NULL))
);

CREATE INDEX idx_notification_pending_due ON pdm_notification_outbox(next_attempt_at, id)
    WHERE state = 'PENDING';
CREATE INDEX idx_alert_unacknowledged_age ON pdm_alert_event(created_at, id) WHERE status = 0;
CREATE INDEX idx_notification_state_id ON pdm_notification_outbox(state, id DESC);
