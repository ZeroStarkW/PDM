CREATE TABLE pdm_maintenance_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES pdm_device(id),
    title VARCHAR(128) NOT NULL,
    interval_days INTEGER NOT NULL CHECK (interval_days BETWEEN 1 AND 36500),
    next_due_at TIMESTAMPTZ NOT NULL,
    instructions VARCHAR(2000),
    assignee VARCHAR(80),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE pdm_maintenance_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT REFERENCES pdm_maintenance_plan(id),
    device_id BIGINT NOT NULL REFERENCES pdm_device(id),
    plan_title VARCHAR(128),
    instructions VARCHAR(2000),
    due_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    assignee VARCHAR(80),
    findings VARCHAR(2000),
    action VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    CONSTRAINT uk_maintenance_task_occurrence UNIQUE (plan_id, due_at)
);

CREATE INDEX idx_maintenance_plan_due ON pdm_maintenance_plan(next_due_at, id);
CREATE INDEX idx_maintenance_plan_enabled_due ON pdm_maintenance_plan(next_due_at, id) WHERE enabled;
CREATE INDEX idx_maintenance_task_due ON pdm_maintenance_task(due_at, id);
CREATE INDEX idx_maintenance_task_active_due ON pdm_maintenance_task(due_at, id)
    WHERE status IN ('OPEN', 'IN_PROGRESS');
CREATE INDEX idx_maintenance_task_history ON pdm_maintenance_task(updated_at DESC, id DESC)
    WHERE status IN ('COMPLETED', 'CANCELLED');
