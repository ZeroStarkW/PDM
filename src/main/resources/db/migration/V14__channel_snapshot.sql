-- 多模态快速事件快照（协议 2.1.0 §2.2）：断路器行程曲线 / 调节阀回环曲线等突发点阵
CREATE TABLE pdm_channel_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id BIGINT NOT NULL REFERENCES pdm_measurement_point(id) ON DELETE CASCADE,
    trigger_type VARCHAR(32) NOT NULL CHECK (trigger_type IN ('TRIP_ACTION_BURST','THRESHOLD_EXCEEDED','SCHEDULED','ON_DEMAND')),
    sampled_at TIMESTAMPTZ NOT NULL,
    sampling_rate DOUBLE PRECISION,
    points_count INTEGER,
    storage_type VARCHAR(32) NOT NULL DEFAULT 'LOCAL_VOLUME',
    storage_ref VARCHAR(512),
    snapshot_url VARCHAR(512),
    preview JSONB NOT NULL,
    curves JSONB,
    curve_units JSONB,
    metrics JSONB,
    annotations JSONB,
    health_index DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_channel_snapshot_point_time ON pdm_channel_snapshot(point_id, sampled_at DESC);
