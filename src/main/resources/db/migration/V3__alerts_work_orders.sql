CREATE TABLE pdm_alert_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id BIGINT NOT NULL REFERENCES pdm_measurement_point(id),
    device_id BIGINT NOT NULL REFERENCES pdm_device(id),
    alert_level VARCHAR(16) NOT NULL CHECK(alert_level IN ('WARNING', 'DANGER')),
    health_index NUMERIC(5,2) NOT NULL,
    dominant_factor VARCHAR(128) NOT NULL,
    trigger_amp NUMERIC(10,4) NOT NULL,
    base_amp NUMERIC(10,4) NOT NULL,
    status SMALLINT NOT NULL DEFAULT 0,
    notified BOOLEAN NOT NULL DEFAULT FALSE,
    occurrence_count INTEGER NOT NULL DEFAULT 1,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_alert_device_status ON pdm_alert_event(device_id, status);
CREATE INDEX idx_alert_point_level_time ON pdm_alert_event(point_id, alert_level, created_at DESC);

CREATE TABLE pdm_work_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL UNIQUE REFERENCES pdm_alert_event(id),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN', 'IN_PROGRESS', 'CLOSED', 'SUPPRESSED')),
    assignee VARCHAR(80),
    resolution_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ
);

CREATE INDEX idx_work_order_status_created ON pdm_work_order(status, created_at DESC);
