CREATE TABLE pdm_diagnostic_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_type_id BIGINT NOT NULL REFERENCES pdm_device_type(id) ON DELETE CASCADE,
    metric VARCHAR(32) NOT NULL CHECK (metric IN (
        'FREQ_1X_AMP', 'FREQ_1X_RATIO', 'FREQ_1X_OVER_2X_RATIO', 'FREQ_2X_AMP', 'FREQ_2X_OVER_1X_RATIO',
        'V_RMS', 'A_PEAK', 'A_KURTOSIS', 'ENVELOPE_RMS', 'TEMPERATURE', 'ORDER_PEAK_AMPLITUDE', 'ORDER_PEAK_SNR'
    )),
    frequency_order DOUBLE PRECISION,
    comparison_operator VARCHAR(3) NOT NULL CHECK (comparison_operator IN ('GT', 'GTE', 'LT', 'LTE')),
    threshold DOUBLE PRECISION NOT NULL CHECK (threshold > '-Infinity'::double precision AND threshold < 'Infinity'::double precision),
    priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 10000),
    factor VARCHAR(128) NOT NULL,
    evidence VARCHAR(512) NOT NULL,
    advice VARCHAR(512) NOT NULL,
    enabled BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_diagnostic_rule_nonnegative_threshold CHECK (metric = 'TEMPERATURE' OR threshold >= 0),
    CONSTRAINT chk_diagnostic_rule_frequency_order CHECK (
        (metric IN ('ORDER_PEAK_AMPLITUDE', 'ORDER_PEAK_SNR') AND frequency_order IS NOT NULL
            AND frequency_order BETWEEN 0.25 AND 20)
        OR (metric NOT IN ('ORDER_PEAK_AMPLITUDE', 'ORDER_PEAK_SNR') AND frequency_order IS NULL)
    )
);

CREATE INDEX idx_diagnostic_rule_type_priority ON pdm_diagnostic_rule(device_type_id, priority DESC, id);

