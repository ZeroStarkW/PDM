CREATE TABLE pdm_baseline_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id BIGINT NOT NULL REFERENCES pdm_measurement_point(id) ON DELETE CASCADE,
    sampled_at TIMESTAMPTZ NOT NULL,
    freq_1x_amp DOUBLE PRECISION NOT NULL,
    v_rms DOUBLE PRECISION NOT NULL,
    a_peak DOUBLE PRECISION NOT NULL,
    a_kurtosis DOUBLE PRECISION,
    temperature DOUBLE PRECISION,
    quality_code SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_point_sample_time UNIQUE(point_id, sampled_at)
);

CREATE INDEX idx_baseline_sample_point_time ON pdm_baseline_sample(point_id, sampled_at);

CREATE TABLE pdm_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pdm_user_role (
    user_id BIGINT NOT NULL REFERENCES pdm_user(id) ON DELETE CASCADE,
    role VARCHAR(16) NOT NULL,
    PRIMARY KEY(user_id, role),
    CONSTRAINT ck_user_role CHECK(role IN ('ADMIN', 'OPERATOR', 'VIEWER'))
);
