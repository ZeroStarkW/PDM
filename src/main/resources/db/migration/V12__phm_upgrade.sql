-- PHM 升级（协议 2.0.0）：轴承几何字典库、测点轴承绑定、原始波形快照、
-- 告警确定性根因明细与 CMMS 工单派单扩展

-- 1. 国际标准滚动轴承几何参数字典库
CREATE TABLE pdm_bearing_library (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(64) NOT NULL UNIQUE,
    manufacturer VARCHAR(32) NOT NULL DEFAULT 'GENERIC',
    ball_count INTEGER NOT NULL CHECK(ball_count > 0),
    ball_diameter NUMERIC(6,3) NOT NULL CHECK(ball_diameter > 0),
    pitch_diameter NUMERIC(7,3) NOT NULL CHECK(pitch_diameter > 0),
    contact_angle_deg NUMERIC(4,1) NOT NULL DEFAULT 0.0 CHECK(contact_angle_deg >= 0 AND contact_angle_deg < 90),
    bpfo_factor NUMERIC(6,4) NOT NULL CHECK(bpfo_factor > 0),
    bpfi_factor NUMERIC(6,4) NOT NULL CHECK(bpfi_factor > 0),
    bsf_factor NUMERIC(6,4) NOT NULL CHECK(bsf_factor > 0),
    ftf_factor NUMERIC(6,4) NOT NULL CHECK(ftf_factor > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. 测点绑定轴承型号（可空，绑定后启用包络谱 BPFO/BPFI 故障线与特征频率诊断）
ALTER TABLE pdm_measurement_point
    ADD COLUMN bearing_model_id BIGINT REFERENCES pdm_bearing_library(id) ON DELETE SET NULL;

CREATE INDEX idx_point_bearing_model ON pdm_measurement_point(bearing_model_id);

-- 3. 原始波形快照（越限触发 / 定时巡检 / 专家召唤）
CREATE TABLE pdm_waveform_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id BIGINT NOT NULL REFERENCES pdm_measurement_point(id) ON DELETE CASCADE,
    trigger_type VARCHAR(32) NOT NULL CHECK(trigger_type IN ('THRESHOLD_EXCEEDED', 'SCHEDULED', 'ON_DEMAND')),
    sampled_at TIMESTAMPTZ NOT NULL,
    sampling_rate DOUBLE PRECISION NOT NULL CHECK(sampling_rate > 0),
    points_count INTEGER NOT NULL CHECK(points_count > 0),
    unit VARCHAR(16) NOT NULL DEFAULT 'm/s^2',
    storage_type VARCHAR(32) NOT NULL DEFAULT 'LOCAL_VOLUME',
    storage_ref VARCHAR(512),
    preview JSONB NOT NULL,
    health_index DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_waveform_point_time ON pdm_waveform_snapshot(point_id, sampled_at DESC);

-- 4. 告警：确定性根因明细（贡献率/恶化倍率/动力学乘子）与关联波形
ALTER TABLE pdm_alert_event
    ADD COLUMN defect_detail JSONB,
    ADD COLUMN raw_snapshot_url VARCHAR(512);

-- 5. 工单：优先级、建议维修措施与备件清单（CMMS 派单）
ALTER TABLE pdm_work_order
    ADD COLUMN priority VARCHAR(16) NOT NULL DEFAULT 'MEDIUM' CHECK(priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    ADD COLUMN maintenance_action TEXT,
    ADD COLUMN spare_parts JSONB;

